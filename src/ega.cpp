void Machine::render() {
    int w = ega.width(), h = ega.height();
    if (fb_w != w || fb_h != h) { fb_w = w; fb_h = h; }
    framebuffer.assign((size_t)w * h, 0xFF000000u);

    if (ega.graphics()) {
        for (int y = 0; y < h; y++) {
            for (int x = 0; x < w; x++) {
                int bytecol = x >> 3;
                int bit = 7 - (x & 7);
                int off = y * 40 + bytecol;   // 320/8 = 40 bytes per row
                uint8_t pix = 0;
                for (int p = 0; p < 4; p++)
                    pix |= ((ega.plane[p][off & 0xFFFF] >> bit) & 1) << p;
                uint8_t ci = ega.attr_pal[pix & 0x0F] & 0x3F;
                uint8_t c[3]; ega_rgb(ci, c);
                framebuffer[(size_t)y * w + x] =
                    0xFF000000u | ((uint32_t)c[0] << 16) | ((uint32_t)c[1] << 8) | c[2];
            }
        }
    } else {
        // text mode: 80x25 cells of 8x8 (from B800:0000)
        uint32_t base = 0xB8000;
        for (int cy = 0; cy < 25; cy++) {
            for (int cx = 0; cx < 80; cx++) {
                uint32_t o = base + (cy * 80 + cx) * 2;
                uint8_t ch = rb(o), at = rb(o + 1);
                int fg = at & 0x0F, bg = (at >> 4) & 0x07;
                if (at & 0x80) { int t = fg; fg = bg; bg = t; }
                const uint8_t* g = (ch >= 32 && ch < 128) ? kFont8x8[ch - 32] : kFont8x8[0];
                for (int gy = 0; gy < 8; gy++) {
                    for (int gx = 0; gx < 8; gx++) {
                        int px = cx * 8 + gx;
                        int py = cy * 8 + gy;
                        if (px >= w || py >= h) continue;
                        bool on = g[gy] & (0x80 >> gx);
                        uint8_t ci = on ? fg : bg;
                        uint8_t c[3]; ega_rgb(ega.attr_pal[ci & 0x0F], c);
                        framebuffer[(size_t)py * w + px] =
                            0xFF000000u | ((uint32_t)c[0] << 16) | ((uint32_t)c[1] << 8) | c[2];
                    }
                }
            }
        }
    }
    fb_dirty = true;
}

