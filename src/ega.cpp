// EGA DAC colours are 6-bit.  Bits 0/1/2 are the primary B/G/R guns (weight 2)
// and bits 3/4/5 the secondary B/G/R guns (weight 1); each gun is a 2-bit level
// 0..3 scaled to 0, 85, 170, 255.  (So index 7 = light gray, 0x38 = dark gray.)
static inline void ega_rgb(int idx, uint8_t* out) {
    idx &= 0x3F;
    out[0] = (uint8_t)(((idx >> 2) & 1) * 170 + ((idx >> 5) & 1) * 85);  // R
    out[1] = (uint8_t)(((idx >> 1) & 1) * 170 + ((idx >> 4) & 1) * 85);  // G
    out[2] = (uint8_t)(((idx >> 0) & 1) * 170 + ((idx >> 3) & 1) * 85);  // B
}

void Ega::reset() {
    for (int i = 0; i < 4; i++) plane[i].assign(0x10000, 0);
    seq_index = gc_index = crtc_index = attr_index = 0;
    seq_map_mask = 0x0F; seq_mem_mode = 0;
    gc_setres = gc_enable_setres = gc_comp = gc_rot = 0;
    gc_read_map = 0; gc_mode = 0; gc_misc = 0; gc_bitmask = 0xFF; gc_xor = 0;
    for (int i = 0; i < 4; i++) gc_latch[i] = 0;
    gc_latch_valid = false;
    for (int i = 0; i < 32; i++) crtc[i] = 0;
    attr_flip = false;
    set_default_palette();
}

void Ega::set_default_palette() {
    for (int i = 0; i < 16; i++) attr_pal[i] = (uint8_t)i;
    attr_overscan = 0;
    attr_color_select = 0;
}

int Ega::width() const {
    if (graphics()) return 320;
    return 640;
}
int Ega::height() const {
    if (graphics()) return 200;
    return 350;
}
int Ega::bpp() const {
    return graphics() ? 4 : 1;
}

uint8_t Ega::read_plane(uint32_t off, int p) {
    off &= 0xFFFF;
    return plane[p & 3][off];
}

uint8_t Ega::read(uint32_t off) {
    off &= 0xFFFF;
    for (int i = 0; i < 4; i++) gc_latch[i] = plane[i][off];
    gc_latch_valid = true;
    return plane[gc_read_map & 3][off];
}

void Ega::write(uint32_t off, uint8_t v) {
    { static unsigned rowc[200]={0}; static long tot=0; static bool reg=false; if(!reg){reg=true;atexit([]{ fprintf(stderr,"[rowc] "); for(int i=0;i<200;i+=10) fprintf(stderr,"%d:%u ",i,rowc[i]); fprintf(stderr,"\n"); });} if(off<8000){ rowc[off/40]++; } }
    writes++;

    if (getenv("LOF_VTRACE")) { static long n=0; static unsigned lo[4]={0xFFFF,0xFFFF,0xFFFF,0xFFFF}, hi[4]={0,0,0,0}; static unsigned nz[4]={0,0,0,0}, tot[4]={0,0,0,0};
        int pp=-1; for(int q=0;q<4;q++) if(seq_map_mask&(1<<q)) pp=q;
        if(pp>=0){ unsigned o=off&0xFFFF; if(o<lo[pp])lo[pp]=o; if(o>hi[pp])hi[pp]=o; tot[pp]++; if(v)nz[pp]++; }
        n++; if(n%20000==0) for(int q=0;q<4;q++) fprintf(stderr,"[vr] plane%d lo=%04X hi=%04X tot=%u nz=%u\n",q,lo[q],hi[q],tot[q],nz[q]); }
    if (getenv("LOF_WMODE")) { static unsigned long keycnt[65536]={0}; unsigned k=((seq_map_mask&0xF)<<12)|((gc_mode&3)<<10)|((gc_enable_setres&0xF)<<6)|(gc_bitmask&0x3F); keycnt[k]++; static long n=0; if(++n%10000==0){ for(int i=0;i<65536;i++) if(keycnt[i]) fprintf(stderr,"[wm] mask=%X mode=%d en=%X bm=%02X cnt=%lu\n",(i>>12)&0xF,(i>>10)&3,(i>>6)&0xF,(i&0x3F),keycnt[i]); } }
    off &= 0xFFFF;
    uint8_t data = v;
    // rotate (GC reg 3 bits 3-5) + logical op (bits 0-1)
    int rot = gc_rot & 7;
    int logop = (gc_rot >> 3) & 3;
    if (rot) data = (uint8_t)((data >> rot) | (data << (8 - rot)));
    for (int p = 0; p < 4; p++) {
        if (!(seq_map_mask & (1 << p))) continue;
        uint8_t val;
        int wmode = gc_mode & 3;
        if (wmode == 1) {               // write mode 1: copy latched pixels
            val = gc_latch[p];
        } else if (wmode == 2) {        // write mode 2: CPU bits select latch pixels
            val = 0;
            for (int b = 0; b < 8; b++)
                if (data & (0x80 >> b)) val |= (gc_latch[p] & (0x80 >> b));
        } else if (gc_enable_setres & (1 << p)) {
            val = (uint8_t)((gc_setres >> p) & 1 ? 0xFF : 0x00);
        } else {
            val = data;
        }
        uint8_t m = gc_bitmask;
        uint8_t old = plane[p][off];
        uint8_t nv;
        switch (logop) {
            case 0: nv = val; break;                       // copy
            case 1: nv = (uint8_t)(val & old); break;      // AND
            case 2: nv = (uint8_t)(val | old); break;      // OR
            default: nv = (uint8_t)(val ^ old); break;     // XOR
        }
        plane[p][off] = (uint8_t)((old & ~m) | (nv & m));
    }
    gc_latch_valid = false;
}

