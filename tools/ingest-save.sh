#!/usr/bin/env bash
# ingest-save.sh — file an owner-supplied save into saves/ WITHOUT overwriting.
#
# The owner drops saves (any name, usually GAME<n>) into saves/inbox/ or the
# repo root.  This script identifies each file by its content hash and files it
# under a descriptive, content-unique name in saves/:
#
#   <map>-<party-lead>-<md5 first 8>.sav        e.g. dng05-Decker-3cf7cace.sav
#
# Rules (see saves/README.md):
#   * identical bytes (same md5) already archived  -> skipped (never duplicated)
#   * a different save that happens to share a name -> kept, suffixed by md5
#   * an existing archived file is NEVER overwritten or deleted
#   * saves/manifest.tsv is regenerated from what is actually in saves/
#
# Usage:
#   tools/ingest-save.sh                 # ingest saves/inbox/* and ./GAME*
#   tools/ingest-save.sh FILE [FILE...]  # ingest specific files
#   tools/ingest-save.sh --check         # report what would happen, change nothing
set -u

ROOT="$(cd "$(dirname "$0")/.." && pwd)"
cd "$ROOT"
SAVES="saves"
INBOX="$SAVES/inbox"
MANIFEST="$SAVES/manifest.tsv"

CHECK=0
if [ "${1:-}" = "--check" ]; then CHECK=1; shift; fi

say() { printf '[ingest] %s\n' "$*" >&2; }

rebuild_manifest() {
    # The manifest is derived from what is on disk (the source of truth).
    python3 - "$MANIFEST" <<'PY'
import glob, os, sys
sys.path.insert(0, "tools")
from saveinfo import parse
out = sys.argv[1]
lines = ["# Auto-generated by tools/ingest-save.sh — do not edit by hand.",
         "# file\tmd5\tsize\tlocation\ttime_of_day\tmorale\tparty"]
for f in sorted(glob.glob("saves/*.sav")):
    i = parse(f)
    if i is None:
        continue
    lines.append("%s\t%s\t%d\t%s\t%d\t%d\t%s" % (
        os.path.basename(f), i["md5"], i["size"], i["map"],
        i["tod"], i["morale"], ", ".join(i["party"])))
open(out, "w").write("\n".join(lines) + "\n")
PY
    say "manifest updated: $MANIFEST"
}

if [ $# -gt 0 ]; then
    inputs=("$@")
else
    inputs=()
    for f in "$INBOX"/* ./GAME[0-9]* ./GAME[0-9]*.SAV ./GAME[0-9]*.sav; do
        [ -f "$f" ] && inputs+=("$f")
    done
fi

if [ ${#inputs[@]} -gt 0 ]; then
    : # fall through to the ingest loop
else
    say "nothing to ingest (no files in $INBOX/ or ./GAME*)"
    [ "$CHECK" = 1 ] && exit 0
    rebuild_manifest
    exit 0
fi

mkdir -p "$SAVES"

added=0 skipped=0 rejected=0
for src in "${inputs[@]}"; do
    [ -f "$src" ] || continue
    info="$(python3 tools/saveinfo.py "$src" 2>/dev/null)"
    if [ -z "$info" ] || ! printf '%s' "$info" | grep -q '^  md5'; then
        say "SKIP   $src (not a Legend of Faerghail save)"
        rejected=$((rejected + 1))
        continue
    fi
    md5="$(printf '%s\n' "$info" | awk '/^  md5/{print $2}')"
    slug="$(printf '%s\n' "$info" | awk '/^  name/{print $2}')"
    short="${md5:0:8}"
    dest="$SAVES/${slug}-${short}.sav"

    # Content already archived?  Same md5 anywhere in saves/ -> nothing to do.
    existing=""
    for f in "$SAVES"/*.sav; do
        [ -f "$f" ] || continue
        [ "$(md5sum "$f" | cut -d' ' -f1)" = "$md5" ] && existing="$f" && break
    done
    if [ -n "$existing" ]; then
        say "DUP    $src == $(basename "$existing") (md5 $short) — not re-filed"
        skipped=$((skipped + 1))
        continue
    fi

    if [ -e "$dest" ]; then
        # Same slug, different content: the md5 suffix makes this unreachable in
        # practice, but never clobber a different file even if it is.
        dest="$SAVES/${slug}-${md5}.sav"
    fi
    if [ -e "$dest" ]; then
        say "REFUSE $dest already exists with different content — not overwriting"
        rejected=$((rejected + 1))
        continue
    fi

    if [ "$CHECK" = 1 ]; then
        say "WOULD  $src -> $dest"
        added=$((added + 1))
        continue
    fi
    cp -p "$src" "$dest" || { say "ERROR  could not copy $src"; rejected=$((rejected + 1)); continue; }
    say "ADDED  $src -> $dest"
    added=$((added + 1))
done

if [ "$CHECK" = 0 ]; then
    rebuild_manifest
fi

say "done: $added added, $skipped duplicate, $rejected rejected"
[ "$rejected" -eq 0 ] || exit 1
